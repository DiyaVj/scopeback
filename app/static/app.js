async function loadHealth() {
  try {
    const response = await fetch('/api/health'); const data = await response.json();
    const pill = $('connection-pill');
    if (data.ollama_connected && data.model_installed) {
      pill.className = 'connection-pill connected';
      $('connection-text').textContent = `Local AI · ${data.model}`;
      pill.title = `Connected to Ollama at ${data.base_url}`;
    } else if (data.ollama_connected) {
      pill.className = 'connection-pill error';
      $('connection-text').textContent = `Install ${data.model}`;
      pill.title = `Ollama is running at ${data.base_url}, but model ${data.model} was not found.`;
    } else {
      pill.className = 'connection-pill error';
      $('connection-text').textContent = 'Local AI not connected';
      pill.title = data.error || 'Ollama was not found.';
    }
  } catch (_) {
    $('connection-pill').className = 'connection-pill error';
    $('connection-text').textContent = 'API unavailable';
  }
}

async function readTextFile(input, targetTextarea) {
  const file = $(input).files?.[0];
  if (!file) return;
  const ext = file.name.split('.').pop().toLowerCase();
  if (ext === 'pdf') {
    // PDF text extraction happens server-side; keep the File object for FormData upload.
    showToast('PDF selected — its text will be extracted when you run the audit.');
    return;
  }
  if (file.size > 5 * 1024 * 1024) {
    showError('File is larger than 5 MB. Choose a smaller file.'); $(input).value = ''; return;
  }
  try {
    $(targetTextarea).value = await file.text(); updateCounters(); clearError();
  } catch (_) { showError('Could not read that file as text.'); }
}

function normalizeFinding(finding, index) {
  return {
    ...finding,
    uiId: `finding-${index}`,
    review_status: finding.review_status || 'needs_review',
    hours: Math.max(0, Number(finding.hours) || 0),
  };
}
function renderList(id, items, fallback) {
  const content = items?.length ? items : [fallback];
  $(id).innerHTML = content.map(item => `<li>${escapeHtml(item)}</li>`).join('');
}
function renderResults(result) {
  state.result = result;
  state.hourlyRate = Number($('hourly-rate').value) || 0;
  state.findings = (result.findings || []).map(normalizeFinding);
  $('results-section').classList.remove('hidden');
  $('results-subtitle').textContent = `${result.message_count || 0} source messages · Review findings before using them.`;
  const modeNotice = $('mode-notice');
  if (result.mode === 'illustrative_demo') {
    modeNotice.textContent = 'Sample report · These findings are illustrative and were not generated by your local model.';
    modeNotice.className = 'mode-notice sample';
  } else {
    modeNotice.textContent = `Analyzed with ${result.model || 'your configured local model'} · Source evidence is verified against the conversation export.`;
    modeNotice.className = 'mode-notice';
  }
  $('findings-list').innerHTML = state.findings.map(renderFinding).join('');
  renderList('agreed-scope-list', result.agreed_scope, 'No scope summary was returned. Review the original agreement manually.');
  renderList('limitations-list', result.limitations, 'Review the complete agreement and billing history before acting.');
  updateTotals();
  setTimeout(() => $('results-section').scrollIntoView({ behavior:'smooth', block:'start' }), 60);
}
function renderFinding(f, index) {
  const cl = f.classification || 'unclear';
  const classificationText = cl === 'potential_scope_change' ? 'POTENTIAL SCOPE CHANGE' : cl === 'in_scope' ? 'LIKELY IN SCOPE' : 'NEEDS CONTEXT';
  const iconClass = cl === 'potential_scope_change' ? '' : cl === 'in_scope' ? 'in-scope' : 'unclear';
  const iconChar = cl === 'potential_scope_change' ? '↗' : cl === 'in_scope' ? '✓' : '?';
  const evidence = (f.evidence || []).map(e => `<div class="evidence-item"><span class="evidence-id">${escapeHtml(e.message_id)}</span>${e.timestamp ? `<span class="evidence-sender">${escapeHtml(e.timestamp)} · </span>` : ''}<span class="evidence-sender">${escapeHtml(e.sender)}:</span> <span class="evidence-text">${escapeHtml(e.text)}</span></div>`).join('');
  const statusOptions = [
    ['needs_review','Needs review'],
    ['confirmed_extra','Confirmed extra work'],
    ['in_scope','Included in original scope'],
    ['already_billed','Already billed / approved'],
    ['not_applicable','Not applicable / not completed'],
  ];
  const options = statusOptions.map(([value,label]) => `<option value="${value}" ${f.review_status===value?'selected':''}>${label}</option>`).join('');
  return `<article class="finding-card" data-index="${index}">
    <div class="finding-main"><div class="finding-top"><div class="finding-title-wrap"><span class="finding-icon ${iconClass}">${iconChar}</span><div><h4>${escapeHtml(f.title)}</h4><p>${escapeHtml(f.summary)}</p></div></div><span class="classification-pill ${iconClass}">${classificationText}</span></div>
    <div class="finding-meta"><span class="meta-chip">Confidence: ${escapeHtml(f.confidence || 'unknown')}</span><span class="meta-chip">${(f.source_message_ids || []).length} source ${(f.source_message_ids || []).length === 1 ? 'message' : 'messages'}</span></div></div>
    <div class="evidence-box"><div class="evidence-head"><span>Source evidence</span><span>${(f.evidence || []).length} reference${(f.evidence || []).length===1?'':'s'}</span></div>${evidence || '<div class="evidence-item">No verified evidence. Treat this as non-actionable.</div>'}<div class="scope-ref"><strong>Agreement reference:</strong> ${escapeHtml(f.scope_reference || 'No matching agreement clause identified')}</div></div>
    <div class="review-controls"><div><label class="review-status-label" for="status-${index}">Your review decision</label><select id="status-${index}" data-field="review_status" data-index="${index}">${options}</select></div><div><label class="review-status-label" for="hours-${index}">Extra hours confirmed</label><div class="hours-input-wrap"><input id="hours-${index}" type="number" min="0" max="100000" step="0.5" value="${Number(f.hours)||0}" data-field="hours" data-index="${index}" aria-label="Extra hours confirmed"/><span>hrs</span></div></div><div class="finding-value" id="value-${index}">₹0<small>potential value</small></div></div>
  </article>`;
}
function updateTotals() {
  const rate = Number($('hourly-rate').value) || 0;
  state.hourlyRate = rate;
  const confirmed = state.findings.filter(f => f.review_status === 'confirmed_extra');
  const total = confirmed.reduce((sum, f) => sum + (Number(f.hours) || 0) * rate, 0);
  $('total-count').textContent = state.findings.length;
  $('potential-count').textContent = state.findings.filter(f => f.classification === 'potential_scope_change').length;
  $('value-total').textContent = currency(total);
  state.findings.forEach((f, i) => {
    const amount = f.review_status === 'confirmed_extra' ? (Number(f.hours)||0) * rate : 0;
    const el = $(`value-${i}`);
    if (el) {
      el.innerHTML = `${escapeHtml(currency(amount))}<small>${f.review_status === 'confirmed_extra' ? 'your estimate' : 'not counted yet'}</small>`;
      el.style.color = f.review_status === 'confirmed_extra' ? 'var(--green)' : 'var(--muted)';
    }
  });
}

$('findings-list').addEventListener('change', (event) => {
  const el = event.target; const index = Number(el.dataset.index); const field = el.dataset.field;
  if (!field || !state.findings[index]) return;
  if (field === 'hours') {
    const value = Number(el.value);
    state.findings[index].hours = Number.isFinite(value) ? Math.min(100000, Math.max(0, value)) : 0;
  } else if (field === 'review_status') {
    state.findings[index].review_status = el.value;
    const parent = el.closest('.finding-card');
    if (parent) parent.classList.toggle('confirmed-card', el.value === 'confirmed_extra');
  }
  updateTotals();
});
$('findings-list').addEventListener('input', (event) => {
  const el = event.target;
  if (el.dataset.field !== 'hours') return;
  const index = Number(el.dataset.index); if (!state.findings[index]) return;
  const value = Number(el.value); state.findings[index].hours = Number.isFinite(value) ? Math.min(100000, Math.max(0, value)) : 0;
  updateTotals();
});

async function analyze() {
  clearError();
  const quoteText = $('quote-text').value.trim(); const messagesText = $('messages-text').value.trim();
  const quoteFile = $('quote-file').files?.[0]; const messagesFile = $('messages-file').files?.[0];
  if (!quoteText && !quoteFile) { showError('Add the project quote or choose a file first.'); $('quote-text').focus(); return; }
  if (!messagesText && !messagesFile) { showError('Add a conversation export or paste the client conversation first.'); $('messages-text').focus(); return; }
  const rate = Number($('hourly-rate').value) || 0;
  if (rate < 0) { showError('Hourly rate cannot be negative.'); return; }
  const button = $('analyze-button'); const oldHTML = button.innerHTML;
  button.disabled = true; button.innerHTML = '<span class="loading-spinner"></span><span>Reviewing scope and evidence…</span>';
  try {
    const form = new FormData();
    form.append('quote_text', quoteText); form.append('messages_text', messagesText); form.append('hourly_rate', String(rate));
    if (quoteFile) form.append('quote_file', quoteFile);
    if (messagesFile) form.append('messages_file', messagesFile);
    const response = await fetch('/api/analyze', { method:'POST', body:form });
    const data = await response.json();
    if (!response.ok) throw new Error(data.detail || `Analysis failed (${response.status})`);
    renderResults(data); showToast('Audit complete. Review each finding before acting.');
  } catch (error) {
    showError(error.message || 'Could not analyze this project. Check that the app and Ollama are running.');
  } finally { button.disabled = false; button.innerHTML = oldHTML; }
}

