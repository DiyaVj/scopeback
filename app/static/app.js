function escapeHtml(value) {
  return String(value ?? '').replace(/[&<>"']/g, ch => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[ch]));
}
function currency(value) {
  return new Intl.NumberFormat('en-IN', { style:'currency', currency:'INR', maximumFractionDigits:0 }).format(Number(value) || 0);
}
function showToast(message) {
  const toast = $('toast'); toast.textContent = message; toast.classList.add('show');
  clearTimeout(state.nextToast); state.nextToast = setTimeout(() => toast.classList.remove('show'), 3000);
}
function showError(message) { $('error-box').textContent = message; $('error-box').classList.remove('hidden'); }
function clearError() { $('error-box').textContent = ''; $('error-box').classList.add('hidden'); }
